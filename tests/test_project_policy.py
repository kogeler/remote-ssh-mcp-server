from __future__ import annotations

import re
import tomllib
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
PIN = re.compile(r"^([A-Za-z0-9][A-Za-z0-9._-]*)==([^\s\\]+)\s+\\$")
HASH = re.compile(r"^--hash=sha256:([0-9a-f]{64})(?:\s+\\)?$")
DIRECT = re.compile(r"^([A-Za-z0-9][A-Za-z0-9._-]*)(?:\[[^]]+\])?==([^\s;]+)$")


def _normalize(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).casefold()


def _workflow_document(name: str) -> dict[str, object]:
    document = yaml.load(
        (ROOT / ".github/workflows" / name).read_text(encoding="utf-8"),
        Loader=yaml.BaseLoader,
    )
    assert isinstance(document, dict)
    return document


def _workflow_steps(document: dict[str, object]) -> tuple[dict[str, object], ...]:
    jobs = document.get("jobs")
    assert isinstance(jobs, dict)
    steps: list[dict[str, object]] = []
    for job in jobs.values():
        assert isinstance(job, dict)
        raw_steps = job.get("steps", [])
        assert isinstance(raw_steps, list)
        for step in raw_steps:
            assert isinstance(step, dict)
            steps.append(step)
    return tuple(steps)


def _direct(requirements: object) -> dict[str, str]:
    assert isinstance(requirements, list)
    result: dict[str, str] = {}
    for requirement in requirements:
        assert isinstance(requirement, str)
        match = DIRECT.fullmatch(requirement)
        assert match is not None, requirement
        name = _normalize(match.group(1))
        assert name not in result
        result[name] = match.group(2)
    return result


def _lock(
    path: Path, *, extra: str | None = None
) -> tuple[dict[str, str], dict[str, set[str]]]:
    content = path.read_text(encoding="utf-8")
    assert "This file is autogenerated by pip-compile" in content
    assert "--allow-unsafe" in content
    assert "--generate-hashes" in content
    assert "--no-emit-find-links" in content
    assert "--strip-extras" in content
    if extra is not None:
        assert f"--extra={extra}" in content

    pins: dict[str, str] = {}
    package_hashes: dict[str, set[str]] = {}
    current: str | None = None

    for line in content.splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue
        if line[:1].isspace():
            match = HASH.fullmatch(stripped)
            assert match is not None and current is not None, (path, line)
            assert match.group(1) not in package_hashes[current], (path, line)
            package_hashes[current].add(match.group(1))
            continue
        match = PIN.fullmatch(line)
        assert match is not None, (path, line)
        current = _normalize(match.group(1))
        assert current not in pins, (path, current)
        pins[current] = match.group(2)
        package_hashes[current] = set()
    assert pins and all(package_hashes.values())
    return pins, package_hashes


def test_hash_locks_match_exact_dependency_owners_and_published_wheel() -> None:
    project = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))
    lint_project = tomllib.loads(
        (ROOT / "tools/lint/pyproject.toml").read_text(encoding="utf-8")
    )
    runtime_direct = _direct(project["project"]["dependencies"])
    optional = project["project"]["optional-dependencies"]
    assert set(optional) == {"dev", "docs", "standalone"}
    development_direct = runtime_direct | _direct(optional["dev"])
    docs_direct = runtime_direct | _direct(optional["docs"])
    standalone_direct = runtime_direct | _direct(optional["standalone"])
    lint_direct = _direct(lint_project["project"]["dependencies"])

    runtime, runtime_hashes = _lock(ROOT / "requirements.txt")
    development, development_hashes = _lock(ROOT / "requirements-dev.txt", extra="dev")
    lint, _lint_hashes = _lock(ROOT / "requirements-lint.txt")
    standalone, standalone_hashes = _lock(
        ROOT / "requirements-standalone.txt", extra="standalone"
    )
    docs, docs_hashes = _lock(ROOT / "requirements-docs.txt", extra="docs")

    assert runtime_direct.items() <= runtime.items()
    assert development_direct.items() <= development.items()
    assert lint == lint_direct
    assert standalone_direct.items() <= standalone.items()
    assert docs_direct.items() <= docs.items()
    wrapper_version = runtime_direct["ssh-wrapper"]
    assert runtime["ssh-wrapper"] == wrapper_version
    assert development["ssh-wrapper"] == wrapper_version
    assert standalone["ssh-wrapper"] == wrapper_version
    assert docs["ssh-wrapper"] == wrapper_version
    wrapper_hashes = runtime_hashes["ssh-wrapper"]
    assert development_hashes["ssh-wrapper"] == wrapper_hashes
    assert standalone_hashes["ssh-wrapper"] == wrapper_hashes
    assert docs_hashes["ssh-wrapper"] == wrapper_hashes


