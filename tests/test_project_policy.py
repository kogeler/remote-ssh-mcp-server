def test_active_workflows_are_complete_pinned_and_root_native() -> None:
    workflow_directory = ROOT / ".github/workflows"
    workflows = tuple(sorted(workflow_directory.glob("*.yml")))
    assert workflows
    external_actions: list[str] = []
    for path in workflows:
        document = _workflow_document(path.name)
        assert document.get("permissions") == {"contents": "read"}
        for step in _workflow_steps(document):
            action = step.get("uses")
            if not isinstance(action, str) or action.startswith("./"):
                continue
            external_actions.append(action)
            assert re.fullmatch(r"[^@\s]+@[0-9a-f]{40}", action)
            if action.startswith("actions/checkout@"):
                options = step.get("with")
                assert isinstance(options, dict)
                assert options.get("persist-credentials") == "false"
                assert "repository" not in options
    assert external_actions


def test_pr_body_is_the_only_pull_request_target_write_boundary() -> None:
    workflow_directory = ROOT / ".github/workflows"
    documents = {
        path.name: _workflow_document(path.name)
        for path in sorted(workflow_directory.glob("*.yml"))
    }
    target_workflows = [
        document
        for document in documents.values()
        if "pull_request_target" in document.get("on", {})
    ]
    assert len(target_workflows) == 1
    workflow = target_workflows[0]
    trigger = workflow["on"]["pull_request_target"]
    assert trigger["branches"] == ["main"]
    assert trigger["paths"] == ["CHANGELOG.md"]

    write_boundaries: list[dict[str, object]] = []
    for document in documents.values():
        jobs = document.get("jobs")
        assert isinstance(jobs, dict)
        for job in jobs.values():
            assert isinstance(job, dict)
            permissions = job.get("permissions", {})
            assert isinstance(permissions, dict)
            if permissions.get("pull-requests") == "write":
                write_boundaries.append(job)
    assert len(write_boundaries) == 1
    assert write_boundaries[0] in workflow["jobs"].values()

    for step in _workflow_steps(workflow):
        action = step.get("uses")
        if not isinstance(action, str) or not action.startswith("actions/checkout@"):
            continue
        options = step.get("with")
        assert isinstance(options, dict)
        assert "ref" not in options


def test_pages_builds_prs_but_deploys_only_trusted_main() -> None:
    workflow = _workflow_document("pages.yml")
    triggers = workflow["on"]
    permissions = workflow["permissions"]
    jobs = workflow["jobs"]
    assert isinstance(triggers, dict)
    assert isinstance(permissions, dict)
    assert isinstance(jobs, dict)

    assert set(triggers) == {"pull_request", "push", "workflow_dispatch"}
    assert triggers["pull_request"]["branches"] == ["main"]
    assert triggers["push"]["branches"] == ["main"]
    assert permissions == {"contents": "read"}

    build = jobs["build"]
    deploy = jobs["deploy"]
    assert isinstance(build, dict) and isinstance(deploy, dict)
    assert "permissions" not in build
    assert deploy["needs"] == "build"
    assert deploy["permissions"] == {"pages": "write", "id-token": "write"}
    deployment_condition = deploy["if"]
    assert isinstance(deployment_condition, str)
    assert "github.event_name == 'push'" in deployment_condition
    assert "github.ref == 'refs/heads/main'" in deployment_condition

    build_steps = build["steps"]
    deploy_steps = deploy["steps"]
    assert isinstance(build_steps, list) and isinstance(deploy_steps, list)
    build_actions = {step.get("uses", "") for step in build_steps}
    deploy_actions = {step.get("uses", "") for step in deploy_steps}
    assert any(
        action.startswith("actions/upload-pages-artifact@") for action in build_actions
    )
    assert any(action.startswith("actions/deploy-pages@") for action in deploy_actions)


