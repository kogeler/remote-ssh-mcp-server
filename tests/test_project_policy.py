def test_release_publishes_only_the_two_gated_executables_and_checksums() -> None:
    """Release reuses CI bytes and verifies a closed standalone inventory."""
    workflow = _workflow_document("release.yml")
    jobs = workflow.get("jobs")
    assert isinstance(jobs, dict)

    reusable_ci = [
        job
        for job in jobs.values()
        if isinstance(job, dict) and job.get("uses") == "./.github/workflows/ci.yml"
    ]
    assert len(reusable_ci) == 1
    inputs = reusable_ci[0].get("with")
    assert isinstance(inputs, dict)
    assert inputs.get("upload_release_artifacts") == "true"

    publishing_jobs = [
        job
        for job in jobs.values()
        if isinstance(job, dict)
        and isinstance(job.get("permissions"), dict)
        and job["permissions"].get("contents") == "write"
    ]
    assert len(publishing_jobs) == 1
    downloads = [
        step
        for step in publishing_jobs[0].get("steps", [])
        if isinstance(step, dict)
        and isinstance(step.get("uses"), str)
        and str(step["uses"]).startswith("actions/download-artifact@")
    ]
    artifact_names = {
        step["with"]["name"]
        for step in downloads
        if isinstance(step.get("with"), dict) and "name" in step["with"]
    }
    assert artifact_names == {"standalone-amd64", "standalone-arm64"}


